static constexpr int TINY_W = 3;
static constexpr int TINY_CELL = 4;  // 3 columns + 1 of spacing

// The tiny font carries digits and capitals only. A slash earns its place
// because the side gutters count things -- "3/5" -- and without it the pair
// reads as two unrelated numbers with a hole between them.
static const uint8_t FONT3X5_SLASH[3] = {0x18, 0x0E, 0x03};
// A hyphen, because a board's name is "esp-red" and a gap where the dash
// should be reads as two names rather than one.
static const uint8_t FONT3X5_DASH[3] = {0x04, 0x04, 0x04};

int Screen::textTiny(int x, int y, const char *s, bool on) {
  for (; *s; s++) {
    // Folded to capitals rather than dropped. There is one case in this font
    // and the panels are all capitals anyway, so a name typed in the browser
    // as "nirvek" has to draw as NIRVEK -- before this it drew as nothing at
    // all, which read as an empty row rather than as a player.
    char c = *s;
    if (c >= 'a' && c <= 'z') c -= 'a' - 'A';
    const uint8_t *g = nullptr;
    if (c >= '0' && c <= '9') g = FONT3X5_DIGIT[c - '0'];
    else if (c >= 'A' && c <= 'Z') g = FONT3X5_ALPHA[c - 'A'];
    else if (c == '/') g = FONT3X5_SLASH;
    else if (c == '-') g = FONT3X5_DASH;
    if (g) {
      for (int col = 0; col < TINY_W; col++)
        for (int row = 0; row < 5; row++)
          if (g[col] & (1 << row)) pixel(x + col, y + row, on);
    }
    x += TINY_CELL;
  }
  return x;
}

int Screen::textTinyWidth(const char *s) {
  int n = 0;
  for (; *s; s++) n++;
  return n ? n * TINY_CELL - 1 : 0;
}

int Screen::textScaled(int x, int y, const char *s, int scale, bool on) {
  if (scale <= 1) return text(x, y, s, on);
  const int left = x;
  for (; *s; s++) {
    if (*s == '\n') { x = left; y += CELL_H * scale; continue; }
    unsigned char c = (unsigned char)*s;
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *g = FONT5X7[c - 0x20];
    for (int col = 0; col < 5; col++)
      for (int row = 0; row < 7; row++)
        if (g[col] & (1 << row))
          fillRect(x + col * scale, y + row * scale, scale, scale, on);
    x += CELL_W * scale;
  }
  return x;
}

// Two strokes, thickened by drawing each one twice a pixel apart, so the mark
// reads at a glance from across a table rather than as a hairline.
int centerScaledX(const char *s, int scale) {
  int w = Screen::textScaledWidth(s, scale);
  if (w > 0) w -= scale;  // the trailing gap after the last glyph
  return (W - w) / 2;
}

int centerTextX(const char *s) { return centerScaledX(s, 1); }

int centerTinyIn(const char *s, int left, int right) {
  int w = Screen::textTinyWidth(s);
  if (w > 0) w -= 1;  // the trailing gap after the last glyph
  return left + (right - left + 1 - w) / 2;
}

void drawTick(Screen &s, int x, int y, int size, bool on) {
  if (size < 4) return;
  const int shortArm = size / 3;      // down-right into the elbow
  const int longArm = size - shortArm;
  const int elbowX = x + shortArm, elbowY = y + size - 1;
  for (int d = 0; d < 2; d++) {
    for (int i = 0; i < shortArm; i++)
      s.pixel(x + i, elbowY - shortArm + 1 + i + d, on);
    for (int i = 0; i < longArm; i++)
      s.pixel(elbowX + i, elbowY - i + d, on);
  }
}

void drawCross(Screen &s, int x, int y, int size, bool on) {
  if (size < 4) return;
  for (int d = 0; d < 2; d++)
    for (int i = 0; i < size; i++) {
      s.pixel(x + i, y + i + d, on);
      s.pixel(x + size - 1 - i, y + i + d, on);
    }
}

