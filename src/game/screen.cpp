static constexpr int CELL_W = 6;   // 5 columns + 1 of spacing
static constexpr int CELL_H = 8;

int Screen::text(int x, int y, const char *s, bool on) {
  const int left = x;
  for (; *s; s++) {
    if (*s == '\n') { x = left; y += CELL_H; continue; }
    unsigned char c = (unsigned char)*s;
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *g = FONT5X7[c - 0x20];
    for (int col = 0; col < 5; col++)
      for (int row = 0; row < 7; row++)
        if (g[col] & (1 << row)) pixel(x + col, y + row, on);
    x += CELL_W;
  }
  return x;
}

int Screen::textWidth(const char *s) {
  int w = 0, best = 0;
  for (; *s; s++) {
    if (*s == '\n') { w = 0; continue; }
    w += CELL_W;
    if (w > best) best = w;
  }
  return best;
}

// The outline is the set of unlit pixels that touch a lit one, so the letter
// keeps its scaled shape and gains a border without growing into its
// neighbours. A scratch Screen holds the solid form while it is traced.
int Screen::textBubble(int x, int y, const char *s, int scale, bool on) {
  static Screen scratch;  // 1KB, not on the stack: the ESP32's is small.
  scratch.clear();
  const int end = scratch.textScaled(x, y, s, scale, true);

  const int h = 7 * scale;
  for (int py = y - 1; py <= y + h; py++) {
    for (int px = x - 1; px <= end; px++) {
      if (scratch.pixelAt(px, py)) continue;
      bool edge = false;
      for (int dy = -1; dy <= 1 && !edge; dy++)
        for (int dx = -1; dx <= 1 && !edge; dx++)
          if (scratch.pixelAt(px + dx, py + dy)) edge = true;
      if (edge) pixel(px, py, on);
    }
  }
  return end;
}

