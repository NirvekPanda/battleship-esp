// Straight to the lobby list, before anything is polled. The title asks
// ONLINE or OFFLINE, which is a question a browser has already answered by
// being a browser -- and leaving it up meant the first press after typing a
// name was swallowed by it, taking the player to the connecting page instead
// of into a lobby.
selectPage(PAGE.rooms);
await connect();     // join the lobby; a seat comes later, from being paired
void roomLoop();     // the five lobbies, drawn on the top panel by the core

// ---- walking back into a match ----------------------------------------
//
// The board as it stands, rather than the log replayed: a result means "the
// shot you just fired", and a page that has just been reloaded fired nothing.
// The relay answers with marks that name their own cell (TMark / TDamage /
// TTurn), which the core applies without firing or answering anything.
//
// The cursor comes back with it: everything in the log is already accounted
// for in the position, so polling from the start would replay the whole match
// on top of it.
let pollCursor = 0;

async function reconnect(): Promise<boolean> {
  try {
    const res = await fetch("/v1/reconnect", { headers: { "X-Peer-Token": peerToken } });
    if (!res.ok) return false;
    const body = await res.json();
    const packets = (body.packets ?? []) as Array<
      { v: number; seq: number; src: number; dst: number; t: number; a: number; b: number }
    >;
    if (packets.length === 0) return false;
    for (const p of packets) sim._sim_receive(p.v, p.seq, p.src, p.dst, p.t, p.a, p.b);
    pollCursor = body.next ?? 0;
    console.info(`relay: rejoined lobby ${body.room} -- ${packets.length} frames of board`);
    return true;
  } catch (err) {
    console.info("relay: reconnect failed", err);
    return false;
  }
}

// ---- carrying packets ----
// The core holds no transport, so this moves them: whatever the relay has for
// us is pushed in, and whatever the core wants to say is drained out and
// posted. Both directions are pumped from the animation loop below, except
// the poll, which parks on the server until something happens.

// One poll loop at a time, and it belongs to one seat.
//
// The loop parks on the server for up to 25 seconds, so it cannot be stopped
// by clearing a token: the reply lands long after. Each loop therefore keeps
// the token it was started for and stops the moment that is no longer the
// current one -- which is what leaving a match, or losing a seat, does. Two
// loops on one seat would double-deliver every packet, and a loop from the
// last match would feed it into a core that has been cleared.
let pollGeneration = 0;

async function pollForever() {
  const mine = ++pollGeneration;
  const seat = peerToken;
  // From wherever the reconnect left the cursor: everything before it is
  // already in the position the relay handed back. It is reset with the seat,
  // so the next match starts reading its log from the beginning rather than
  // skipping the Start packets that opened it.
  let cursor = pollCursor;
  // A long poll answers the moment the opponent moves, so a shot appears as
  // fast as the network allows rather than on some local timer.
  for (;;) {
    if (mine !== pollGeneration || peerToken !== seat) return;
    try {
      const res = await fetch(`/v1/recv?since=${cursor}`, {
        headers: { "X-Peer-Token": seat },
      });
      // The seat is gone -- the relay restarted, or the seats were cleared.
      // Claim a new one rather than retrying a token nobody recognises for
      // ever, which is what the firmware does too.
      // The seat is gone: the relay restarted, or -- the ordinary case now --
      // the match ended and its room was cleared. Either way this game is
      // over, so the core is reset and the player goes back to the lobby
      // list. Keeping the board would show the last match's ships and shots
      // in what is meant to be a fresh game.
      if (res.status === 401) {
        // The verdict first. A match ends by the relay clearing the lobby,
        // which invalidates the seat -- so the 401 that tells us the game is
        // over arrives a moment after the WIN or LOSE goes up, and resetting
        // on it took the answer off the screen before it could be read.
        if (sim._sim_page() === PAGE.over) {
          for (let i = 0; i < 24 && sim._sim_page() === PAGE.over; i++) {
            // Or until they press: the verdict is worth a few seconds, not an
            // argument about how long.
            if (i > 2 && (inputMask() & M.center) !== 0) break;
            await new Promise((r) => setTimeout(r, 250));
          }
        }
        console.info("relay: seat lost, back to the lobby");
        peerToken = "";
        myRoom = 0;
        pollCursor = 0;   // the next match reads its own log from the start
        sim._sim_begin();
        sim._sim_set_my_room(0);
        sim._sim_set_link(LINK.connecting);
        selectPage(PAGE.rooms);
        await connect();
        void roomLoop();
        return;
      }
      if (!res.ok) throw new Error(`recv: ${res.status}`);
      const body = await res.json();
      cursor = body.next;
      for (const p of body.packets) {
        sim._sim_receive(p.v, p.seq, p.src, p.dst, p.t, p.a, p.b);
      }
      // Still there. Say so, or a single earlier hiccup would leave the core
      // believing the link is down for the rest of the session.
      sim._sim_set_link(LINK.online);
    } catch (err) {
      // Connecting, not offline. Offline means "there is no network here" and
      // the core takes it as licence to play alone; a hiccup on one poll is
      // nothing of the sort, and treating it that way would drop the player
      // into a solo game while their opponent waits.
      console.info("relay: poll failed, retrying", err);
      sim._sim_set_link(LINK.connecting);
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
}

// Drain whatever the core produced this frame. Reading the pointer before
// calling again matters: it points at one static buffer inside the module.
// Everything the core produced this frame, in one request.
//
// Laying out a fleet produces six packets at once, and the placement code
// states the invariant outright: Ready is last, so a peer that sees Ready
// knows every Fleet is already behind it. Six separate fetches handed that
// ordering to the browser's connection pool, which does not know about it.
// One request keeps the order and costs one round trip instead of six --
// which is what the firmware has always done with its octet-stream batch.
function flushOutbound() {
  if (!peerToken) return;
  const batch: Array<Record<string, number>> = [];
  for (;;) {
    const ptr = sim._sim_take_outbound();
    if (!ptr) break;
    const w = sim.HEAPU8.subarray(ptr, ptr + 8);
    // The layout of record: v, t, src, dst, seq lo, seq hi, a, b.
    // See server/PROTOCOL.md and game::packWire().
    batch.push({
      v: w[0],
      t: w[1],
      src: w[2],
      dst: w[3],
      seq: w[4] | (w[5] << 8),
      a: w[6],
      b: w[7],
    });
  }
  if (batch.length === 0) return;

  const seat = peerToken;
  void fetch("/v1/send", {
    method: "POST",
    headers: { "X-Peer-Token": seat, "Content-Type": "application/json" },
    body: JSON.stringify(batch.length === 1 ? batch[0] : batch),
  }).catch((err) => console.info("relay: send failed", err));
}


// --- rendering -------------------------------------------------------------
const ON = [0x33, 0xcc, 0xff, 0xff];   // lit pixel
const OFF = [0x0a, 0x0e, 0x14, 0xff];  // unlit

class Panel {
  private ctx: CanvasRenderingContext2D;
  private img: ImageData;

  constructor(canvas: HTMLCanvasElement, private ptr: () => number) {
    canvas.width = W;
    canvas.height = H;
    const ctx = canvas.getContext("2d");
    if (!ctx) throw new Error("2d context unavailable");
    this.ctx = ctx;
    this.img = ctx.createImageData(W, H);
  }

  // Unpack SSD1306 page format: byte (x + (y/8)*W) holds 8 stacked pixels,
  // LSB topmost -- the exact bytes the real panel would receive over I2C.
  draw() {
    const base = this.ptr();
    const heap = sim.HEAPU8;
    const px = this.img.data;
    for (let y = 0; y < H; y++) {
      const page = (y >> 3) * W;
      const bit = 1 << (y & 7);
      for (let x = 0; x < W; x++) {
        const c = heap[base + page + x] & bit ? ON : OFF;
        const o = (y * W + x) * 4;
        px[o] = c[0]; px[o + 1] = c[1]; px[o + 2] = c[2]; px[o + 3] = c[3];
      }
    }
    this.ctx.putImageData(this.img, 0, 0);
  }
}

const byId = (id: string) => {
  const el = document.getElementById(id);
  if (!(el instanceof HTMLCanvasElement)) throw new Error(`missing canvas #${id}`);
  return el;
};

const panels = [
  new Panel(byId("top"), () => sim._sim_top()),
  new Panel(byId("bottom"), () => sim._sim_bottom()),
];

// Both panels take touches, so whichever one a thumb lands on drives the same
// five buttons -- there is no "controls" half of this page to reach for.
for (const id of ["top", "bottom"]) touchControls(byId(id));

// --- loop ------------------------------------------------------------------

// Debug hook: the page the core is on, for automated tests to read. It is a
// number on a global, not a control -- nothing in the page reads it back.
declare global {
  interface Window {
    __corePage?: number; __myTurn?: number;
    __aim?: [number, number]; __inFlight?: number;
  }
}

function frame(now: number) {
  nameBoxRefresh();
  window.__corePage = sim._sim_page();
  window.__myTurn = sim._sim_my_turn();
  window.__aim = [sim._sim_aim_col(), sim._sim_aim_row()];
  window.__inFlight = sim._sim_in_flight();
  sim._sim_set_input(inputMask());
  // Before the tick, so a press is acted on in the same frame the core sees
  // it move the cursor.
  pumpRoomPress();
  sim._sim_tick(Math.floor(now));
  // Drain after the tick, since that is when the core decides to say
  // something -- a shot fired on this frame goes out on this frame.
  flushOutbound();
  for (const p of panels) p.draw();
  requestAnimationFrame(frame);
}
requestAnimationFrame(frame);
