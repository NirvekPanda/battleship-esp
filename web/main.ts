// --- input -----------------------------------------------------------------
const M = { up: 1, right: 2, down: 4, left: 8, center: 16 };

const KEYS: Record<string, number> = {
  ArrowUp: M.up, ArrowRight: M.right, ArrowDown: M.down, ArrowLeft: M.left,
  KeyW: M.up, KeyD: M.right, KeyS: M.down, KeyA: M.left,
  Space: M.center, Enter: M.center,
};

const held = new Set<string>();

// A key pressed while the name box has focus is a letter being typed, not a
// move: W, A, S, D, space and Enter are all in the map below, so swallowing
// them here is what made half the alphabet impossible to type.
const typing = (e: Event) => {
  const t = e.target;
  return t instanceof HTMLInputElement || t instanceof HTMLTextAreaElement ||
         t instanceof HTMLSelectElement;
};

addEventListener("keydown", (e) => {
  if (typing(e)) return;
  if (!(e.code in KEYS)) return;
  e.preventDefault();  // stop arrows/space from scrolling the page
  held.add(e.code);
});
addEventListener("keyup", (e) => {
  if (typing(e)) return;
  if (e.code in KEYS) { e.preventDefault(); held.delete(e.code); }
});
addEventListener("blur", () => held.clear());  // don't stick keys on tab-out

// ---- touch: the same five buttons, drawn with a finger --------------------
//
// A phone has no 5-way switch, so the gestures stand in for one: a swipe is
// the direction it went, a tap is centre, and holding still is centre held --
// which is what the leave countdown reads. The core is never told about any
// of this; it sees the same five levels it sees from the switch or the keys,
// so a game played with a thumb is the same game.
const touched = { up: false, right: false, down: false, left: false, centre: false };

// How far a finger must travel to be a swipe rather than a tap, and how long
// it must sit still to be a hold rather than a tap. 24px is about a fingertip
// of slop; 250ms is comfortably under the double press, so tapping twice to
// place a ship never becomes a hold.
const SWIPE_PX = 24;
const HOLD_TOUCH_MS = 250;

// A swipe is a step, not a level: it sets the direction for one repeat of the
// cursor and then lets go, which is what a flick means. Holding a direction
// is a swipe followed by keeping the finger out there, handled by re-arming
// from the new origin.
const STEP_HOLD_MS = 140;

function pulse(key: "up" | "right" | "down" | "left" | "centre", ms: number) {
  touched[key] = true;
  setTimeout(() => { touched[key] = false; }, ms);
}

function touchControls(el: HTMLElement) {
  let x0 = 0, y0 = 0, startedAt = 0, moved = false, holdTimer = 0;

  const end = () => {
    clearTimeout(holdTimer);
    if (touched.centre) {          // a hold, ended by lifting the finger
      touched.centre = false;
      return;
    }
    if (!moved && performance.now() - startedAt < HOLD_TOUCH_MS) {
      pulse("centre", 120);        // a tap is a press
    }
  };

  el.addEventListener("touchstart", (e) => {
    const t = e.changedTouches[0];
    x0 = t.clientX; y0 = t.clientY;
    startedAt = performance.now();
    moved = false;
    e.preventDefault();            // no scrolling, no double-tap zoom
    // Still after a moment: the finger is holding the button down, which is
    // what the countdown to leaving a match reads.
    holdTimer = window.setTimeout(() => {
      if (!moved) touched.centre = true;
    }, HOLD_TOUCH_MS);
  }, { passive: false });

  el.addEventListener("touchmove", (e) => {
    const t = e.changedTouches[0];
    const dx = t.clientX - x0, dy = t.clientY - y0;
    if (Math.abs(dx) < SWIPE_PX && Math.abs(dy) < SWIPE_PX) return;
    e.preventDefault();
    moved = true;
    clearTimeout(holdTimer);
    touched.centre = false;        // a swipe is not a press
    // The bigger movement wins, so a diagonal drag is read as the direction
    // it mostly went rather than as two directions at once.
    if (Math.abs(dx) > Math.abs(dy)) pulse(dx > 0 ? "right" : "left", STEP_HOLD_MS);
    else pulse(dy > 0 ? "down" : "up", STEP_HOLD_MS);
    // Re-armed from here, so keeping the finger moving keeps stepping.
    x0 = t.clientX; y0 = t.clientY;
  }, { passive: false });

  el.addEventListener("touchend", (e) => { e.preventDefault(); end(); }, { passive: false });
  el.addEventListener("touchcancel", () => { clearTimeout(holdTimer); touched.centre = false; });
}

function inputMask(): number {
  let m = 0;
  for (const code of held) m |= KEYS[code];
  if (touched.up) m |= M.up;
  if (touched.right) m |= M.right;
  if (touched.down) m |= M.down;
  if (touched.left) m |= M.left;
  if (touched.centre) m |= M.center;
  return m;
}

