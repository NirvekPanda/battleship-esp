// ---- reset ----
// sim_begin() re-runs Game::begin(), which clears the fleet, the tracking
// grid and every cursor -- the same call the firmware makes at power-on, so a
// reset here leaves the core in exactly the state a fresh boot would.
export function resetGame() {
  sim._sim_begin();
  selectPage(PAGE.start);
  // Give the seat up too. Resetting the core while a token was still live
  // left the tab polling a match it had erased, with nothing to put it back
  // on the lobby list.
  if (peerToken) {
    void leaveRoom();
  } else if (!roomLoopRunning) {
    void roomLoop();
  }
}

el("btn-reset", HTMLButtonElement).addEventListener("click", resetGame);

// ---- the name box --------------------------------------------------------
//
// A name can be changed while you are in the lobby and not while you are
// playing: it is who the relay thinks is at the table, and swapping it under
// a running match would leave the other player looking at somebody who no
// longer exists. So the box shadows out the moment a game starts.
//
// Changing it starts you over, which is what the warning says. There is no
// halfway version of this -- the name travels with the join, the seat and the
// board -- so the honest implementation goes back to the beginning and comes
// in again as that player.
function wireNameBox() {
  const box = el("btn-name", HTMLInputElement);
  const save = el("btn-save", HTMLButtonElement);
  const warn = el("nameWarn", HTMLParagraphElement);

  // Whether the player has typed in it. Tracked rather than inferred from a
  // comparison with the current name, so filling the box in from the name we
  // already know does not look like an edit -- which is what left it empty.
  let dirty = false;

  const refresh = () => {
    const playing = peerToken !== "";
    box.disabled = playing;
    if (!dirty && document.activeElement !== box) box.value = playerName;
    const show = dirty && !playing && cleanName(box.value).trim() !== playerName;
    save.hidden = !show;
    warn.hidden = !show;
  };

  box.addEventListener("input", () => {
    const fixed = cleanName(box.value);
    if (fixed !== box.value) {
      const at = Math.min(box.selectionStart ?? fixed.length, fixed.length);
      box.value = fixed;
      box.setSelectionRange(at, at);
    }
    dirty = true;
    refresh();
  });

  save.addEventListener("click", async () => {
    const name = cleanName(box.value).trim() || "player";
    store.set(localStorage, "playerName", name);
    // Stand up from whatever lobby this player is sitting in first, so the
    // row does not keep showing a name nobody answers to, then start again.
    try {
      await fetch("/v1/rooms/leave", { method: "POST", headers: idHeaders() });
    } catch {
      /* the reload puts us back in the lobby either way */
    }
    location.reload();
  });

  nameBoxRefresh = refresh;
  refresh();
}

// ---- the link ----
// The relay serves this page, so it is always at the same origin and needs no
// address configuring. Claiming a seat is what tells the core the link is up;
// the connecting page then moves on by itself.
//
// A failure here is not fatal and must not be: with no relay running the page
// still plays perfectly well on its own, so the core is told Offline and the
// connecting page says so and invites a press to carry on.
let peerToken = "";
let selfPeer = 0;

// ---- who this player is -------------------------------------------------
//
// A UUID made once and kept, so the server can tell two players apart when
// they pick the same name -- and can recognise this one again after a reload,
// which is what makes reconnecting to a running match possible at all. The
// name is only a label.
// Storage that cannot throw. A private window, or a browser set to block site
// data, makes every one of these calls raise -- and at module level that
// stops the whole page evaluating, so neither canvas is ever created and the
// tab is blank with only a console line to explain it. The game plays
// perfectly well with nothing remembered; it does not play at all if reading
// a preference can kill the module.
const store = {
  get(where: Storage, key: string): string | null {
    try {
      return where.getItem(key);
    } catch {
      return null;
    }
  },
  set(where: Storage, key: string, value: string) {
    try {
      where.setItem(key, value);
    } catch {
      /* nothing is remembered; everything still works */
    }
  },
  drop(where: Storage, key: string): boolean {
    try {
      where.removeItem(key);
      return true;
    } catch {
      return false;
    }
  },
};

// A v4 UUID, without requiring a secure context.
//
// crypto.randomUUID() exists only on HTTPS and localhost. The relay now binds
// the whole WiFi, and a phone opening the page by the laptop's LAN address is
// therefore in an INSECURE context -- where that function is simply not
// defined, and the page died on the line that called it before either canvas
// was drawn. crypto.getRandomValues() carries no such restriction, so the
// bytes come from there and only the formatting is done here; Math.random is
// the last resort, and being able to play is worth more than the quality of
// an id that only has to be different from the other players in the room.
function makePlayerId(): string {
  const bytes = new Uint8Array(16);
  if (typeof crypto !== "undefined" && typeof crypto.getRandomValues === "function") {
    crypto.getRandomValues(bytes);
  } else {
    for (let i = 0; i < bytes.length; i++) bytes[i] = Math.floor(Math.random() * 256);
  }
  bytes[6] = (bytes[6] & 0x0f) | 0x40;   // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80;   // variant 1
  const hex = [...bytes].map((b) => b.toString(16).padStart(2, "0"));
  return [
    hex.slice(0, 4).join(""),
    hex.slice(4, 6).join(""),
    hex.slice(6, 8).join(""),
    hex.slice(8, 10).join(""),
    hex.slice(10, 16).join(""),
  ].join("-");
}

const PLAYER_ID = (() => {
  // Per TAB, not per browser. localStorage is shared by every tab of the same
  // origin, so two tabs there are one player as far as the relay can tell --
  // which is exactly why only the most recently opened one ever appeared in
  // the list. sessionStorage is per tab and still survives a reload, which is
  // what reconnecting to a running match needs.
  const saved = store.get(sessionStorage, "playerId");
  if (saved) return saved;
  const made = typeof crypto !== "undefined" && typeof crypto.randomUUID === "function"
    ? crypto.randomUUID()
    : makePlayerId();
  store.set(sessionStorage, "playerId", made);
  return made;
})();

let playerName = store.get(localStorage, "playerName") ?? "";
// Set once the name box exists: the frame loop calls it so the box tracks the
// game -- filled in when the name is known, shadowed out once a match starts.
let nameBoxRefresh: () => void = () => {};
// Red and black are gone from here entirely: they are an ESP32 label, carried
// in a board's own name, because a board has no keyboard to be named with.

const idHeaders = () => ({ "X-Player-Id": PLAYER_ID });

// One name per tab, not per application. The relay lets a client take back a
// seat it already holds -- which is what makes reloading, or reflashing the
// board, work rather than finding the table full of yourself -- and that only
// behaves if two tabs are two different clients.
const clientName = `browser-${Math.random().toString(16).slice(2, 6)}`;

// Keep trying, the way the firmware does. A tab opened before the relay is
// started, or while both seats are briefly held by a stale client, joins as
// soon as one is free rather than being stuck offline until it is reloaded.
// Until then the core is told Offline, so the connecting page says so and
// stays pressable.
// ---- the name modal -----------------------------------------------------
// Asked before anything connects, because the name travels with this player
// to the other side: the connection cannot be made without it.
// What a name may be. The panels draw 16 characters and no more, and the name
// travels to a board inside a line- and pipe-delimited text protocol -- so a
// newline or a pipe in a name is a name that can forge a line of that
// protocol. The relay enforces this too, and has to: a page is not a
// gatekeeper. Doing it here as well is so the player sees the name they will
// actually be given rather than discovering it on someone else's panel.
const NAME_MAX = 16;

function cleanName(raw: string): string {
  let out = "";
  for (const ch of raw) {
    const code = ch.codePointAt(0) ?? 0;
    if (code < 0x20 || code === 0x7f || ch === "|") continue;
    out += ch;
    if ([...out].length >= NAME_MAX) break;
  }
  return out;
}

function askName(): Promise<void> {
  return new Promise((resolve) => {
    const modal = el("nameModal", HTMLDivElement);
    const form = el("nameForm", HTMLFormElement);
    const input = el("nameInput", HTMLInputElement);
    const hint = el("nameHint", HTMLParagraphElement);
    input.maxLength = NAME_MAX;
    input.value = cleanName(playerName);
    modal.hidden = false;
    input.focus();

    // Corrected as it is typed rather than refused on submit: a paste that
    // carries a newline is fixed in front of the player, who then sees what
    // their name is going to be.
    input.addEventListener("input", () => {
      const fixed = cleanName(input.value);
      if (fixed !== input.value) {
        const at = Math.min(input.selectionStart ?? fixed.length, fixed.length);
        input.value = fixed;
        input.setSelectionRange(at, at);
        hint.textContent = `Names are ${NAME_MAX} characters of plain text.`;
        hint.classList.add("bad");
        return;
      }
      hint.classList.remove("bad");
      const left = NAME_MAX - [...fixed].length;
      hint.textContent = left <= 4
        ? `${left} character${left === 1 ? "" : "s"} left.`
        : `Up to ${NAME_MAX} characters \u2014 that is what a panel line holds.`;
    });

    form.addEventListener("submit", (e) => {
      e.preventDefault();
      playerName = cleanName(input.value).trim() || "player";
      store.set(localStorage, "playerName", playerName);
      modal.hidden = true;
      // Focus has to leave the field, not just the screen. Keys typed while
      // an input has focus are letters, not moves -- that is what stops WASD
      // being unusable in the name box -- so a hidden box that kept focus
      // swallowed every press of the game that followed it.
      input.blur();
      if (document.activeElement instanceof HTMLElement) document.activeElement.blur();
      resolve();
    });
  });
}

// ---- the five rooms -----------------------------------------------------
// Drawn by the CORE on the top panel, not by this page: picking a lobby is
// part of the game, so it is the same screen with the same cursor on a board
// and in a browser. The only thing a browser player does that a board cannot
// is type their name.
//
// A full room is refused by the relay, which is the check that counts -- two
// clients pressing centre on the same row in the same instant is what no
// amount of drawing can cover.
type RoomRow = { n: number; players: string[]; yours?: boolean };

let myRoom = 0;

function writeName(buf: number, name: string) {
  const max = sim._sim_lobby_name_max();
  const bytes = new TextEncoder().encode(name).subarray(0, max);
  sim.HEAPU8.set(bytes, buf);
  sim.HEAPU8[buf + bytes.length] = 0;
}

function pushRooms(rooms: RoomRow[]) {
  sim._sim_clear_rooms();
  for (const r of rooms) {
    writeName(sim._sim_room_a_buf(), r.players[0] ?? "");
    writeName(sim._sim_room_b_buf(), r.players[1] ?? "");
    sim._sim_set_room(r.n, r.players.length, r.yours ? 1 : 0);

    // Both players of OUR lobby, by name, so the verdict can say whose win it
    // is. "WIN" is the same word on both panels; a name is not.
    if (r.n === myRoom && r.players.length === 2) {
      const them = r.players.find((n) => n !== playerName) ?? r.players[1];
      writeName(sim._sim_room_a_buf(), playerName);
      writeName(sim._sim_room_b_buf(), them);
      sim._sim_set_names();
    }
  }
  sim._sim_set_my_room(myRoom);
}

let roomLoopRunning = false;

async function roomLoop() {
  if (roomLoopRunning) return;   // one loop, however many ways back in there are
  roomLoopRunning = true;
  try {
    await watchRooms();
  } finally {
    roomLoopRunning = false;
  }
}

async function watchRooms() {
  for (;;) {
    if (peerToken) return;
    // From the title, and from the connecting page too. A press that lands
    // before the first poll answers takes the core off the title by itself --
    // it asks ONLINE or OFFLINE and centre answers it -- and the connecting
    // page then waits for a handshake that the browser never performs, since
    // the browser is paired by the lobby rather than by Join/Ack. Without
    // this, an early press left the tab watching water for ever.
    const on = sim._sim_page();
    if (on === PAGE.start || on === PAGE.connecting) selectPage(PAGE.rooms);
    try {
      const res = await fetch("/v1/rooms", { headers: idHeaders() });
      if (res.ok) {
        const body = await res.json();
        myRoom = body.you ?? 0;
        pushRooms((body.rooms ?? []) as RoomRow[]);
        // Paired. The seat and the token arrive with it, which is the moment
        // this stops being a lobby and becomes a game.
        // A token is what makes it a match: the relay pairs players and hands
        // out seats in two steps, and taking "matched" without one leaves the
        // page on a board it cannot play.
        if (body.matched && body.token && !peerToken) {
          peerToken = body.token;
          selfPeer = body.seat === "b" ? 2 : 1;
          sim._sim_set_self_peer(selfPeer);
          sim._sim_set_link(LINK.online);
          // A match already in progress in this lobby is one we are walking
          // back into: the relay hands the board back and we are put down
          // where we left off. A fresh match has no board to hand back, and
          // starts from placement.
          const restored = await reconnect();
          if (!restored) selectPage(PAGE.place);
          void pollForever();
          return;
        }
      }
    } catch {
      /* the relay being away is already reported by the connecting page */
    }
    await new Promise((r) => setTimeout(r, 1000));
  }
}

// True once the relay knows who we are. A press that lands before that -- the
// player is quicker than the first round trip, which is easy -- is remembered
// rather than dropped: the relay refuses a room join from a player it has not
// been introduced to, and silently losing the press reads as a dead button.
let known = false;
let pendingJoin = 0;

async function joinRoom(n: number) {
  if (!known) {
    pendingJoin = n;
    return;
  }
  try {
    const res = await fetch(`/v1/rooms/join?n=${n}`, {
      method: "POST",
      headers: idHeaders(),
    });
    // A refusal means someone took the second place between the draw and the
    // press; the next poll redraws the row as full.
    if (res.ok) {
      myRoom = n;
      sim._sim_set_my_room(n);
    }
  } catch (err) {
    console.info("rooms: join failed", err);
  }
}

// The gesture belongs to the core -- a press joins the room under the cursor,
// a hold goes back to the list -- so this only carries the decision to the
// relay, exactly as src/main.cpp does on the board. Reading the raw button
// here as well is what let the press that opened the page join room 1 before
// the player had seen the list.
function pumpRoomPress() {
  // The leave is read whether or not we are in a match: holding centre works
  // from every page of a game, and walking out of one is the case that
  // matters most. Only the join is a lobby-list thing.
  if (sim._sim_take_room_leave()) void leaveRoom();
  if (peerToken) return;
  const join = sim._sim_take_room_join();
  if (join) void joinRoom(join);
}

async function leaveRoom() {
  const wasPlaying = peerToken !== "";
  myRoom = 0;
  peerToken = "";          // the seat is given up, so nothing is carried on it
  pollGeneration++;        // and the loop that was reading it stops
  pollCursor = 0;
  sim._sim_set_my_room(0);
  sim._sim_set_link(LINK.connecting);
  try {
    await fetch("/v1/rooms/leave", { method: "POST", headers: idHeaders() });
  } catch (err) {
    console.info("rooms: leave failed", err);
  }
  // Walking out of a match means going back to the list, which is a loop that
  // stopped when the match started. The core has already cleared its own
  // board; this is the transport catching up with it.
  if (wasPlaying) void roomLoop();
}

// The relay is reached through the lobby now, not by claiming a seat. A seat
// is a role in a match, and there is no match until two players have chosen
// each other -- claiming one on arrival is what turned the third person away
// instead of showing them who was here.
async function connect() {
  sim._sim_set_link(LINK.connecting);
  for (;;) {
    try {
      const res = await fetch("/v1/lobby/join", {
        method: "POST",
        headers: { ...idHeaders(), "Content-Type": "application/json" },
        body: JSON.stringify({ name: playerName }),
      });
      if (!res.ok) throw new Error(`lobby: ${res.status}`);
      const body = await res.json();
      console.info(
        `lobby: ${body.player.name}`,
        body.resume ? "-- a match of yours is still running" : "",
      );
      known = true;
      if (pendingJoin) {
        const n = pendingJoin;
        pendingJoin = 0;
        void joinRoom(n);
      }
      return;
    } catch (err) {
      // Offline, not merely connecting. With no relay there is no opponent
      // who could ever arrive, and the connecting page waits for a fact about
      // two machines rather than on a timer -- so a page told "connecting"
      // for ever is a page that can never be played. Offline is what lets the
      // core fall through and play solo, which is the whole point of the
      // simulator working with nothing else running.
      console.info("relay: not reachable, playing offline until it appears", err);
      sim._sim_set_link(LINK.offline);
      await new Promise((r) => setTimeout(r, 3000));
    }
  }
}

// The core is started BEFORE the lobby flow, not after it. Doing it after was
// the bug that hid the lobby: begin() plus a jump to the start page ran once
